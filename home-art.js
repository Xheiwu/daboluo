const HomeArt = {
  cache: new Map(),

  // 返回放大后的离屏 Canvas（按 id+倍率缓存）
  canvas(id, scale = 2) {
    const key = id + '@' + scale;
    if (this.cache.has(key)) return this.cache.get(key);
    const rows = HOME_SPRITES[id];
    if (!rows || typeof document === 'undefined') return null;
    const c = document.createElement('canvas');
    c.width = rows[0].length * scale;
    c.height = rows.length * scale;
    const g = c.getContext('2d');
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      for (let x = 0; x < row.length; x++) {
        const color = HOME_PALETTE[row[x]];
        if (!color) continue;
        g.fillStyle = color;
        g.fillRect(x * scale, y * scale, scale, scale);
      }
    }
    this.cache.set(key, c);
    return c;
  },

  // UI 中使用的图片地址
  dataURL(id, scale = 3) {
    const key = 'url:' + id + '@' + scale;
    if (this.cache.has(key)) return this.cache.get(key);
    const c = this.canvas(id, scale);
    const url = c ? c.toDataURL('image/png') : '';
    this.cache.set(key, url);
    return url;
  },

  img(id, scale = 3, cls = '') {
    const url = this.dataURL(id, scale);
    return url ? `<img class="home-pixel ${cls}" src="${url}" alt="" draggable="false">` : '';
  }
};
